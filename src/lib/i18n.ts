export const DICTS: Record<Lang, Dict> = { zh, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.zh[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** 阶段名称：预设阶段用字典翻译，自定义阶段原样显示 */
export function stageLabel(lang: Lang, stage: string): string {
  return stage.startsWith("stage.") ? translate(lang, stage) : stage;
}
